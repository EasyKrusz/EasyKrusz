const KEY = "lang";
const safeGet = () => { try { return localStorage.getItem(KEY); } catch { return null; } };

/** Wybrany język ("auto" = język przeglądarki). */
export function getLangSetting() {
  const v = safeGet();
  return LANGS.includes(v) ? v : "auto";
}

export function setLangSetting(value) {
  try {
    if (value === "auto") localStorage.removeItem(KEY);
    else localStorage.setItem(KEY, value);
  } catch {}
}

/** Język interfejsu i nowych przepisów. */
export function getLang() {
  const set = getLangSetting();
  if (set !== "auto") return set;
  for (const l of navigator.languages || [navigator.language || "en"]) {
    const code = baseLang(l);
    if (LANGS.includes(code)) return code;
  }
  return "en";
}

/** Kierunek pisma interfejsu – gotowe na przyszłe języki pisane od prawej (np. arabski). */
export const uiDir = () => (isRTL(getLang()) ? "rtl" : "ltr");

/** Język, w którym AI pisze nowe przepisy: język interfejsu, a dla nieobsługiwanych języków przeglądarki – ten język. */
export function getRecipeLang() {
  if (getLangSetting() !== "auto") return getLang();
  return normalizeLangTag(navigator.language || "en");
}

/** Tekst w języku interfejsu; {n} wybiera formę liczby mnogiej. */
export function t(key, vars = {}) {
  const lang = getLang();
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (typeof s === "object") {
    const form = new Intl.PluralRules(lang).select(Number(vars.n ?? 0));
    s = s[form] ?? s.other;
  }
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

/** Nazwa języka w języku interfejsu, np. "ko" → "koreański". */
export function langName(code) {
  try {
    return new Intl.DisplayNames([getLang()], { type: "language" }).of(code) || code;
  } catch {
    return code;
  }
}

